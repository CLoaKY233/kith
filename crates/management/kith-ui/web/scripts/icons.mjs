// Writes src/lib/icons/sprite.svg: the Lucide subset the page uses (spec §5 Icons) plus
// the four custom glyphs, as <symbol>s drawn at 1.5 stroke. Run `npm run icons` after
// changing either list; the sprite is committed.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const LUCIDE = [
  'activity', 'monitor-smartphone', 'list', 'at-sign', 'globe', 'plus', 'settings-2',
  'inbox', 'search', 'copy', 'check', 'ellipsis', 'ban', 'triangle-alert', 'circle-x',
  'qr-code', 'ticket', 'laptop', 'monitor', 'smartphone', 'server', 'cpu', 'key-round',
  'radio-tower', 'pencil', 'arrow-left', 'x', 'chevron-down', 'chevron-right', 'minus',
  'scan', 'network',
];

// Custom glyphs on Lucide's 24-unit grid, same stroke rules.
const CUSTOM = {
  'path-direct': '<path d="M3 12h18"/><circle cx="3" cy="12" r="1.5"/><circle cx="21" cy="12" r="1.5"/>',
  'path-relayed': '<path d="M3 16 12 8l9 8"/><circle cx="3" cy="16" r="1.5"/><rect x="10" y="6" width="4" height="4"/><circle cx="21" cy="16" r="1.5"/>',
  'path-stealth': '<path d="M3 16 12 8l9 8" stroke-dasharray="2 2.5"/><circle cx="3" cy="16" r="1.5"/><rect x="10" y="6" width="4" height="4"/><circle cx="21" cy="16" r="1.5"/>',
  seal: '<path d="M12 2.5 14.6 4.4 17.8 4.3 18.8 7.4 21.4 9.3 20.4 12.4 21.4 15.5 18.8 17.4 17.8 20.5 14.6 20.4 12 22.3 9.4 20.4 6.2 20.5 5.2 17.4 2.6 15.5 3.6 12.4 2.6 9.3 5.2 7.4 6.2 4.3 9.4 4.4Z"/><path d="m8.5 12.4 2.4 2.4 4.6-4.8"/>',
  mark: '<circle cx="6" cy="12" r="3"/><circle cx="18" cy="6" r="3"/><circle cx="18" cy="18" r="3"/><path d="M8.7 10.6 15.3 7.4M8.7 13.4l6.6 3.2"/>',
};

const root = fileURLToPath(new URL('..', import.meta.url));
const symbols = [];
for (const name of LUCIDE) {
  const svg = readFileSync(`${root}node_modules/lucide-static/icons/${name}.svg`, 'utf8');
  const body = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>[\s\S]*$/, '')
    .replace(/\s*\n\s*/g, '')
    .trim();
  symbols.push(`<symbol id="i-${name}" viewBox="0 0 24 24">${body}</symbol>`);
}
for (const [name, body] of Object.entries(CUSTOM)) {
  symbols.push(`<symbol id="i-${name}" viewBox="0 0 24 24">${body}</symbol>`);
}
const header = '<!-- Generated by scripts/icons.mjs. Lucide icons: ISC licence, lucide.dev. -->';
const sprite = `${header}\n<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" style="display:none" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">\n${symbols.join('\n')}\n</svg>\n`;
writeFileSync(`${root}src/lib/icons/sprite.svg`, sprite);

const names = [...LUCIDE, ...Object.keys(CUSTOM)];
writeFileSync(
  `${root}src/lib/icons/names.ts`,
  `// Generated by scripts/icons.mjs. Every icon in sprite.svg.\nexport const ICONS = ${JSON.stringify(names, null, 2).replace(/"/g, "'")} as const;\n\nexport type IconName = (typeof ICONS)[number];\n`,
);
