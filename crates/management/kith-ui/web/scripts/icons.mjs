// Writes src/lib/icons/sprite.svg: the Lucide subset the page uses (spec §5 Icons) plus
// the four custom glyphs and the kith mark, as <symbol>s. Stroke, fill and caps come from
// Icon.svelte, because a <use> instance inherits from where it is used, not from the
// sprite. Run `npm run icons` after changing either list; the sprite is committed.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const LUCIDE = [
  'activity', 'monitor-smartphone', 'list', 'at-sign', 'globe', 'plus', 'settings-2',
  'inbox', 'search', 'copy', 'check', 'ellipsis', 'ban', 'triangle-alert', 'circle-x',
  'qr-code', 'ticket', 'laptop', 'monitor', 'smartphone', 'server', 'cpu', 'key-round',
  'radio-tower', 'pencil', 'arrow-left', 'x', 'chevron-down', 'chevron-right', 'minus',
  'scan', 'network', 'users',
];

// Custom glyphs (spec §5) on Lucide's 24-unit grid with the same stroke rules. Endpoints are
// rings, a relay is a square as on the map (§9.2). Relayed and stealth share the bent path
// through the relay; stealth draws it dotted. The seal is an eight-lobed rosette with a check:
// signed by an admin's key.
const relayed = (legs) =>
  `<circle cx="4.5" cy="17" r="2"/><circle cx="19.5" cy="17" r="2"/>` +
  `<rect x="10" y="4.5" width="4" height="4" rx="0.5"/>` +
  `<path d="M5.6 15.3 10 8.5M18.4 15.3 14 8.5"${legs}/>`;

/** An eight-lobed rosette: each lobe is a quadratic curve bulging past the outer radius. */
function rosette(cx, cy, inner, outer, lobes) {
  const point = (r, a) => `${(cx + r * Math.sin(a)).toFixed(2)} ${(cy - r * Math.cos(a)).toFixed(2)}`;
  const step = (2 * Math.PI) / lobes;
  let d = `M${point(inner, -step / 2)}`;
  for (let i = 0; i < lobes; i += 1) {
    const a = i * step;
    d += `Q${point(outer, a)} ${point(inner, a + step / 2)}`;
  }
  return `${d}Z`;
}

const CUSTOM = {
  'path-direct': '<circle cx="4.5" cy="12" r="2"/><circle cx="19.5" cy="12" r="2"/><path d="M6.5 12h11"/>',
  'path-relayed': relayed(''),
  'path-stealth': relayed(' stroke-dasharray="0.5 2.5"'),
  seal: `<path d="${rosette(12, 12, 8, 11.6, 8)}"/><path d="m8.75 12.25 2.25 2.25 4.25-4.5"/>`,
  mark: '<circle cx="6" cy="12" r="3"/><circle cx="18" cy="6" r="3"/><circle cx="18" cy="18" r="3"/><path d="M8.7 10.6 15.3 7.4M8.7 13.4l6.6 3.2"/>',
};

const root = fileURLToPath(new URL('..', import.meta.url));
const symbols = [];
for (const name of LUCIDE) {
  const svg = readFileSync(`${root}node_modules/lucide-static/icons/${name}.svg`, 'utf8');
  const body = svg
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>[\s\S]*$/, '')
    .replace(/\s*\n\s*/g, '')
    .trim();
  symbols.push(`<symbol id="i-${name}" viewBox="0 0 24 24">${body}</symbol>`);
}
for (const [name, body] of Object.entries(CUSTOM)) {
  symbols.push(`<symbol id="i-${name}" viewBox="0 0 24 24">${body}</symbol>`);
}
const header = '<!-- Generated by scripts/icons.mjs. Lucide icons: ISC licence, lucide.dev. -->';
const sprite = `${header}\n<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" focusable="false" width="0" height="0" style="position:absolute;overflow:hidden">\n${symbols.join('\n')}\n</svg>\n`;
writeFileSync(`${root}src/lib/icons/sprite.svg`, sprite);

const names = [...LUCIDE, ...Object.keys(CUSTOM)];
writeFileSync(
  `${root}src/lib/icons/names.ts`,
  `// Generated by scripts/icons.mjs. Every icon in sprite.svg.\nexport const ICONS = ${JSON.stringify(names, null, 2).replace(/"/g, "'")} as const;\n\nexport type IconName = (typeof ICONS)[number];\n`,
);
