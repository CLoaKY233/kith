//! Linux: iproute2 policy routing (as wg-quick does), systemd-resolved or
//! resolvconf for DNS, and a private nftables table for NAT.

use std::path::Path;

use kith_types::IpPrefix;

use crate::{
    Cmd, Dns, Domain, Error, FWMARK, Interface, Plan, ROUTE_TABLE, System,
    sys::{Errors, Sys, field, lines},
};

const RULE_PRIORITY: u32 = 5260;
const RESOLV_CONF: &str = "/etc/resolv.conf";
const RESOLV_MARKER: &str = "# Generated by kith; the original is restored when kith stops.\n";
const NO_ROUTE: &str = "No such process";
const NO_ENTRY: &str = "No such file or directory";

fn ip(v6: bool) -> Cmd {
    Cmd::new("ip").arg(if v6 { "-6" } else { "-4" })
}

fn route(verb: &str, prefix: &IpPrefix, dev: &Interface) -> Cmd {
    ip(matches!(prefix, IpPrefix::V6(_)))
        .args(["route", verb])
        .arg(prefix)
        .arg("dev")
        .arg(dev)
}

/// Rules evaluated in order: main table without its default route, then
/// unmarked traffic to the kith table. The tunnel's marked UDP skips the second.
fn rules() -> [Vec<String>; 2] {
    [
        format!("table main suppress_prefixlength 0 priority {RULE_PRIORITY}"),
        format!(
            "not fwmark {FWMARK} table {ROUTE_TABLE} priority {}",
            RULE_PRIORITY + 10
        ),
    ]
    .map(|r| r.split(' ').map(str::to_owned).collect())
}

pub(crate) fn apply<S: System>(sys: &mut Sys<S>, plan: &Plan) -> Result<(), Error> {
    let dev = &plan.interface;
    for prefix in &plan.routes {
        sys.run(route("replace", prefix, dev))?;
    }
    if plan.exit_node.is_some() {
        for v6 in [false, true] {
            sys.run(
                ip(v6)
                    .args(["route", "replace", "default", "dev"])
                    .arg(dev)
                    .arg("table")
                    .arg(ROUTE_TABLE),
            )?;
            // `ip rule add` duplicates, so delete first.
            for rule in rules() {
                sys.run(ip(v6).args(["rule", "del"]).args(&rule).tolerate(NO_ENTRY))?;
                sys.run(ip(v6).args(["rule", "add"]).args(&rule))?;
            }
        }
    }
    if let Some(dns) = &plan.dns {
        apply_dns(sys, dev, dns)?;
    }
    if plan.forwarding {
        sys.enable_sysctls(&["net.ipv4.ip_forward", "net.ipv6.conf.all.forwarding"])?;
    }
    if let Some(nat) = plan.nat.as_ref().filter(|n| !n.sources.is_empty()) {
        let cmd = ip(false).args(["route", "show", "default"]);
        let line = cmd.to_string();
        let out = sys.exec(&cmd)?.stdout;
        let wan = field(&out, "dev").ok_or(Error::Parse {
            command: line,
            output: out.clone(),
        })?;
        let wan = Interface::new(wan)?;
        let rules = lines(nat.sources.iter().map(|src| {
            let family = if matches!(src, IpPrefix::V6(_)) {
                "ip6"
            } else {
                "ip"
            };
            format!("\t\toifname \"{wan}\" {family} saddr {src} masquerade")
        }));
        let ruleset = format!(
            "add table inet kith\ndelete table inet kith\ntable inet kith {{\n\tchain postrouting {{\n\t\t\
             type nat hook postrouting priority srcnat; policy accept;\n{rules}\t}}\n}}\n"
        );
        sys.run(Cmd::new("nft").args(["-f", "-"]).stdin(ruleset))?;
    }
    Ok(())
}

pub(crate) fn revert<S: System>(sys: &mut Sys<S>, plan: &Plan, errors: &mut Errors) {
    let dev = &plan.interface;
    errors.keep(
        sys.run(
            Cmd::new("nft")
                .args(["delete", "table", "inet", "kith"])
                .tolerate(NO_ENTRY),
        ),
    );
    errors.keep(sys.restore_sysctls());
    errors.keep(revert_dns(sys, dev));
    for v6 in [false, true] {
        for rule in rules() {
            errors.keep(sys.run(ip(v6).args(["rule", "del"]).args(&rule).tolerate(NO_ENTRY)));
        }
        let flush = ip(v6).args(["route", "flush", "table"]).arg(ROUTE_TABLE);
        errors.keep(sys.run(flush.tolerate("FIB table does not exist")));
    }
    for prefix in &plan.routes {
        errors.keep(sys.run(route("del", prefix, dev).tolerate(NO_ROUTE)));
    }
}

fn has_resolved<S: System>(sys: &mut Sys<S>) -> Result<bool, Error> {
    Ok(sys.system.has_program("resolvectl")
        && !sys
            .system
            .list(Path::new("/run/systemd/resolve"))?
            .is_empty())
}

fn apply_dns<S: System>(sys: &mut Sys<S>, dev: &Interface, dns: &Dns) -> Result<(), Error> {
    if has_resolved(sys)? {
        sys.run(Cmd::new("resolvectl").arg("dns").arg(dev).arg(dns.resolver))?;
        let routing = dns.all.then_some("~.".to_owned());
        let domains: Vec<String> = routing
            .into_iter()
            .chain(dns.domains.iter().map(|d| format!("~{d}")))
            .collect();
        if !domains.is_empty() {
            sys.run(Cmd::new("resolvectl").arg("domain").arg(dev).args(domains))?;
        }
        return sys.run(
            Cmd::new("resolvectl")
                .arg("default-route")
                .arg(dev)
                .arg(dns.all),
        );
    }
    let search = if dns.domains.is_empty() {
        String::new()
    } else {
        lines([format!(
            "search {}",
            dns.domains
                .iter()
                .map(Domain::as_str)
                .collect::<Vec<_>>()
                .join(" ")
        )])
    };
    if sys.system.has_program("resolvconf") {
        let conf = format!("nameserver {}\n{search}", dns.resolver);
        return sys.run(Cmd::new("resolvconf").arg("-a").arg(dev).stdin(conf));
    }
    // Last resort: rewrite /etc/resolv.conf with the mesh resolver first, keeping
    // the original nameservers after it. The original is backed up and restored
    // only if the file still carries our marker, so later edits by others survive.
    let path = Path::new(RESOLV_CONF);
    let current = sys.system.read(path)?;
    let original = match &current {
        Some(text) if text.starts_with(RESOLV_MARKER) => sys
            .read_list(&sys.state("resolv.conf"))?
            .into_iter()
            .skip(1)
            .collect::<Vec<_>>()
            .join("\n"),
        other => {
            let backup = other
                .as_ref()
                .map_or_else(|| "absent\n".to_owned(), |t| format!("present\n{t}"));
            sys.system.write(&sys.state("resolv.conf"), &backup)?;
            other.clone().unwrap_or_default()
        }
    };
    let servers = lines(original.lines().filter(|l| l.starts_with("nameserver")));
    let text = format!(
        "{RESOLV_MARKER}nameserver {}\n{servers}{search}",
        dns.resolver
    );
    sys.system.write(path, &text)
}

fn revert_dns<S: System>(sys: &mut Sys<S>, dev: &Interface) -> Result<(), Error> {
    let mut errors = Errors::default();
    if has_resolved(sys)? {
        let cmd = Cmd::new("resolvectl").arg("revert").arg(dev);
        errors.keep(sys.run(cmd.tolerate("Unknown interface").tolerate("No such device")));
    }
    if sys.system.has_program("resolvconf") {
        errors.keep(sys.run(Cmd::new("resolvconf").arg("-d").arg(dev)));
    }
    let backup_path = sys.state("resolv.conf");
    if let Some(backup) = sys.system.read(&backup_path)? {
        let path = Path::new(RESOLV_CONF);
        if sys
            .system
            .read(path)?
            .is_some_and(|t| t.starts_with(RESOLV_MARKER))
        {
            errors.keep(match backup.strip_prefix("present\n") {
                Some(original) => sys.system.write(path, original),
                None => sys.system.remove(path),
            });
        }
        errors.keep(sys.system.remove(&backup_path));
    }
    errors.finish()
}
